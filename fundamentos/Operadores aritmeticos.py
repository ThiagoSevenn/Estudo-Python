# Ordem de processamento das expressões aritméticas. DICA: É igual a ordem de precedência com expressões matemáticas.
# 1ª ~> ()
# 2ª ~> **
# 3ª ~> * , / , // , %
# 4ª ~> + , -

# Soma (+)
print('Soma de 5+2:',5 + 2)

# Subtração (-)
print('Subtração de 5-2:',5 - 2)

# Multiplicação (*)
print('Multiplição de 5*2:',5 * 2)

# Divisão (/)
print('Divisão de 5/2:',5 / 2)

# Divisão Inteira (//)
print('Divisão inteira de 5/2:',5 // 2)

# Resto da divisão (%)
print('Resto da divisão de 5/2:',5 % 2)

# Potência (**)
print('Potência de 5**2:',5 ** 2)  